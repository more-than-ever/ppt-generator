// 统计口径的数字：百分比、万/亿/倍、"达/超过/提升/增长 + 数字"等
export const STAT_RE = /(?:\d+(?:\.\d+)?\s*(?:[%％‰]|千万|百万|万元|亿元|万人|万台|万辆|万家|万|亿|倍)|(?:达到?|超过?|突破|提升|增长|增至|降至|下降|降低|减少|节省|覆盖)\s*(?:约|近|逾)?\s*\d+(?:\.\d+)?\s*(?:[%％‰]|千万|百万|万元|亿元|万人|万台|万辆|万家|万|亿|倍)?)/;

