export function normalizeText(text) {
  return String(text ?? '').trim();
}

// 只检查来源说明的形式完整性，不声称识别出处真伪。
export function hasSourceDetails(text = '') {
  return /(?:19|20)\d{2}年?/.test(text)
    && /(?:《[^》\n]{3,80}》|[A-Z]{2,12}\s*(?:报告|统计|数据|年报)|[\u4e00-\u9fa5]{2,20}(?:统计局|协会|委员会|研究院|研究所|公司|年报|公报))/.test(text);
}

function statisticTokens(text) {
  return [...String(text || '').matchAll(new RegExp(STAT_RE.source, 'g'))]
    .map(m => m[0].replace(/^[^\d]+/, '').replace(/\s/g, '').replace('％', '%'));
}

// 具体锚点检查：正文条目含数字（数据/年份/编号）即视为有锚点；
// 纯文字空泛评价（"潜力巨大""日益重要"）无锚点。与 contentService 草稿校验配套。
export function lacksConcreteAnchor(text = '') {
  const body = String(text ?? '').replace(/^【[^】]+】[:：]?/, '').trim();
  if (!body) return false; // 空条目由"正文未完成"检查负责
  return !/[0-9０-９]/.test(body);
}

export function findCopyIssues(text, { sourceText = '', checkHollow = true, allowPublicSources = true } = {}) {
  const s = normalizeText(text);
  const issues = [];
  if (isSchemaEcho(s)) issues.push('出现了字段说明而非实际文案');
  if (/(?:[Xx]{1,2}\s*[%％万亿]|某某|待补充|待完善)/.test(s)) issues.push('含未完成的占位内容，应说明已有依据而非补造数值');
  const supplied = new Set(statisticTokens(sourceText));
  // 出处可能位于同一条目的前句或后句；检查条目整体，不拆散引用与事实。
  for (const sentence of s.split(/(?<=[。！？\n])/)) {
    const unknown = statisticTokens(sentence).filter(n => !supplied.has(n));
    if (unknown.length && !(allowPublicSources && hasSourceDetails(s))) {
      issues.push(`统计值${[...new Set(unknown)].join('、')}未在用户资料中出现，也缺少具体出处和时间；请修正整句，不能补造来源`);
    }
  }
  const body = s.replace(/^【[^】]+】[:：]?/, '').trim();
  if (checkHollow && body.length < 45 && /(?:赋能|抓手|共创辉煌|潜力巨大|前景广阔|行业标杆|高质量发展)/.test(body)
    && !/(?:例如|比如|因为|建议|通过|每周|每月|分别|如果|记录|核对|比较)/.test(body)) {
    issues.push('只有笼统评价，需说明具体对象、做法或判断依据；不强迫增加数字或扩成固定字数');
  }
  return issues;
}

// 模型把 JSON 模板里的说明文字当成内容原样返回
const SCHEMA_ECHO_RE = /^(?:本页唯一结论(?:[（(]判断句[）)])?|本页核心信息|本页实际条目|一句话主张|汇报人\/场合|从版式菜单中选一个\s*id|封面副标题|用一两句中文说明为什么选这个版式、阅读顺序与视觉重点|【小标题】：正文|否则留空)$/;

export function isSchemaEcho(str) {
  const s = String(str || '').trim();
  if (!s) return false;
  return SCHEMA_ECHO_RE.test(s);
}
